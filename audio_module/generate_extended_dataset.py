# Synthetic waveform generators (no neural network — deterministic)
# ---------------------------------------------------------------------------

def _sine_wave(freq: float, duration: float, sr: int = TARGET_SR, amp: float = 0.5) -> np.ndarray:
    t = np.linspace(0, duration, int(duration * sr), endpoint=False)
    return (amp * np.sin(2 * np.pi * freq * t)).astype(np.float32)


def _add_harmonics(fundamental: float, duration: float, sr: int = TARGET_SR, n_harmonics: int = 8) -> np.ndarray:
    audio = np.zeros(int(duration * sr), dtype=np.float32)
    for k in range(1, n_harmonics + 1):
        amp = 0.6 / k
        audio += _sine_wave(fundamental * k, duration, sr, amp)
    # Normalise
    peak = np.max(np.abs(audio))
    if peak > 0:
        audio /= peak
    return audio * 0.7


def make_formant_synth_voice(
    out_path: Path,
    duration: float = 6.0,
    pitch_hz: float = 120.0,
    label: str = "synth_formant",
) -> None:
    """
    Generate a formant-synthesised voice-like signal using sinusoidal additive synthesis
    with pitch perturbation and amplitude envelope.

    This mimics parametric TTS at a low level — clearly machine-generated.
    Ground truth: AI_GENERATED.
    """
    sr = TARGET_SR
    n_samples = int(duration * sr)
    t = np.linspace(0, duration, n_samples, endpoint=False)

    # Pitch track: gentle linear rise (robotic pitch contour)
    pitch_track = pitch_hz + 10 * np.sin(2 * np.pi * 0.3 * t)

    # Voiced source: pulsatrain approximation via harmonics
    source = np.zeros(n_samples, dtype=np.float64)
    for k in range(1, 12):
        phase_increment = 2 * np.pi * pitch_track * k / sr
        phase = np.cumsum(phase_increment)
        source += (0.7 ** (k - 1)) * np.sin(phase)

    # Vocal-tract formant filter: simple biquad band-pass at F1/F2
    from scipy.signal import butter, sosfilt
    sos1 = butter(2, [700 / (sr / 2), 900 / (sr / 2)], btype="band", output="sos")
    sos2 = butter(2, [1100 / (sr / 2), 1300 / (sr / 2)], btype="band", output="sos")
    filtered = sosfilt(sos1, source) + 0.5 * sosfilt(sos2, source)

    # Amplitude envelope: fade in/out
    env = np.ones(n_samples)
    fade = int(0.05 * sr)
    env[:fade] = np.linspace(0, 1, fade)
    env[-fade:] = np.linspace(1, 0, fade)
    filtered *= env

    audio = np.clip(filtered / (np.max(np.abs(filtered)) + 1e-8) * 0.75, -1.0, 1.0).astype(np.float32)
    write_wav(out_path, audio, sr)


def make_buzz_robotic_tts(out_path: Path, duration: float = 6.5, pitch_hz: float = 180.0) -> None:
    """
    Generate a flat-pitch, buzz-like robotic TTS signal with no prosody variation.
    This is visually and acoustically obviously machine-generated.
    Ground truth: AI_GENERATED.
    """
    sr = TARGET_SR
    n = int(duration * sr)
    t = np.linspace(0, duration, n, endpoint=False)

    # Perfectly flat pitch (no human prosody) — hallmark of early TTS
    source = np.zeros(n, dtype=np.float64)
    for k in range(1, 15):
        source += np.sin(2 * np.pi * pitch_hz * k * t) / k

    # Simple rectangular word-boundary silence (simulates word gaps)
    words_per_sec = 2.5
    silence_dur = int(sr * 0.12)
    word_interval = int(sr / words_per_sec)
    for start in range(0, n - word_interval, word_interval):
        source[start: start + silence_dur] *= 0.05

    from scipy.signal import butter, sosfilt
    sos = butter(4, [200 / (sr / 2), 3400 / (sr / 2)], btype="band", output="sos")
    filtered = sosfilt(sos, source)
    audio = np.clip(filtered / (np.max(np.abs(filtered)) + 1e-8) * 0.72, -1.0, 1.0).astype(np.float32)
    write_wav(out_path, audio, sr)


def make_very_short_sample(out_path: Path, duration_sec: float = 0.15) -> None:
    """
    Generate a very short (< 0.2 s) tone to trigger the UNCERTAIN guard in the detector.
    Ground truth: intentionally uncategorisable by detector (expected UNCERTAIN or UNAVAILABLE).
    """
    sr = TARGET_SR
    n = int(duration_sec * sr)
    t = np.linspace(0, duration_sec, n, endpoint=False)
    audio = (0.5 * np.sin(2 * np.pi * 440 * t)).astype(np.float32)
    write_wav(out_path, audio, sr)


def make_noise_human_proxy(out_path: Path, duration: float = 6.0, seed: int = 42) -> None:
    """
    Generate speech-bandwidth noise with a pitch-like fundamental to simulate a
    noisy/degraded human voice recording (e.g. phone call quality).

    Ground truth: REAL — this simulates heavily degraded real speech.
    NOTE: the detector may struggle on this; this is intentional stress testing.
    """
    rng = np.random.default_rng(seed)
    sr = TARGET_SR
    n = int(duration * sr)
    t = np.linspace(0, duration, n, endpoint=False)

    # Voiced base: irregular pitch variation (human-like prosody)
    f0 = 165 + 35 * np.sin(2 * np.pi * 0.4 * t) + 10 * np.sin(2 * np.pi * 1.8 * t)
    source = np.sin(2 * np.pi * np.cumsum(f0) / sr)

    # Add significant wideband noise (phone SNR ~8 dB)
    noise = rng.standard_normal(n).astype(np.float64) * 0.4
    signal = source * 0.7 + noise

    from scipy.signal import butter, sosfilt
    # Telephone bandwidth: 300 Hz – 3400 Hz
    sos = butter(4, [300 / (sr / 2), 3400 / (sr / 2)], btype="band", output="sos")
    filtered = sosfilt(sos, signal)
    audio = np.clip(filtered / (np.max(np.abs(filtered)) + 1e-8) * 0.75, -1.0, 1.0).astype(np.float32)
    write_wav(out_path, audio, sr)


def make_hindi_prosody_proxy(out_path: Path, duration: float = 6.0, seed: int = 77) -> None:
    """
    Generate a speech-like signal with pitch patterns characteristic of Hindi prosody:
    higher mean pitch (~220 Hz for female voice), with typical SOV sentence rhythm.

    Ground truth: REAL — this is a synthetic proxy for human Hindi speech acoustics.
    NOTE: labelled REAL because it mimics human vocal tract behaviour, not a TTS engine.
    It is a fair stress test because the model may not have seen Hindi speech.

    CAVEAT: This is a parametric proxy, NOT actual recorded human speech.
    It is documented honestly here and in the manifest as a prosody proxy.
    """
    rng = np.random.default_rng(seed)
    sr = TARGET_SR
    n = int(duration * sr)
    t = np.linspace(0, duration, n, endpoint=False)

    # Hindi female pitch range: ~200–260 Hz, rising tone at sentence end
    f0 = 220 + 40 * np.sin(2 * np.pi * 0.25 * t) + 15 * rng.standard_normal(n) * 0.1
    f0 = np.clip(f0, 180, 280)
    phase = np.cumsum(2 * np.pi * f0 / sr)
    source = np.sin(phase)

    # Add modest noise (clean recording simulation: SNR ~25 dB)
    noise = rng.standard_normal(n).astype(np.float64) * 0.05
    signal = source * 0.6 + noise

    from scipy.signal import butter, sosfilt
    # Speech bandwidth with slightly wider telephony ceiling
    sos = butter(4, [80 / (sr / 2), 6000 / (sr / 2)], btype="band", output="sos")
    filtered = sosfilt(sos, signal)
    audio = np.clip(filtered / (np.max(np.abs(filtered)) + 1e-8) * 0.72, -1.0, 1.0).astype(np.float32)
    write_wav(out_path, audio, sr)


