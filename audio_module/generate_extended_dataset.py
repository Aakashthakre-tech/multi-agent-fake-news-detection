def generate_all() -> list[dict]:
    manifest = []

    for spec in NEW_SAMPLES:
        out_path = EXTENDED_DIR / spec["filename"]
        success = False
        error_msg = None

        print(f"  [{spec['id']}] Generating {spec['filename']}...")

        try:
            method = spec["generation_method"]

            if method == "ffmpeg_mp3_roundtrip":
                src = VALIDATION_DIR / spec["source_file"]
                success = make_compressed_human_proxy(src, out_path, bitrate_kbps=32)
                if not success:
                    error_msg = "ffmpeg MP3 roundtrip failed"

            elif method == "ffmpeg_mp3_roundtrip_64k":
                src = VALIDATION_DIR / spec["source_file"]
                success = make_compressed_human_proxy(src, out_path, bitrate_kbps=64)
                if not success:
                    error_msg = "ffmpeg MP3 roundtrip 64k failed"

            elif method == "scipy_telephone_noise_proxy":
                make_noise_human_proxy(out_path)
                success = True

            elif method == "scipy_formant_synthesis":
                make_formant_synth_voice(out_path, pitch_hz=120.0)
                success = True

            elif method == "scipy_formant_synthesis_female":
                make_formant_synth_voice(out_path, pitch_hz=200.0, label="synth_formant_female")
                success = True

            elif method == "scipy_buzz_robotic":
                make_buzz_robotic_tts(out_path)
                success = True

            elif method == "scipy_hindi_prosody_proxy":
                make_hindi_prosody_proxy(out_path)
                success = True

            elif method == "scipy_short_tone":
                make_very_short_sample(out_path, duration_sec=0.15)
                success = True

            else:
                error_msg = f"Unknown generation method: {method}"

        except Exception as e:
            error_msg = str(e)
            success = False

        file_size = out_path.stat().st_size if out_path.exists() else 0
        entry = {
            **spec,
            "file_path": str(out_path),
            "generated": success,
            "file_size_bytes": file_size,
            "error": error_msg,
        }
        manifest.append(entry)
        status = "OK" if success else f"FAILED: {error_msg}"
        print(f"       -> {status}  ({file_size:,} bytes)")

    return manifest


