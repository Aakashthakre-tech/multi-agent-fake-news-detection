# ---------------------------------------------------------------------------
# Low-level WAV writer
# ---------------------------------------------------------------------------

def write_wav(path: Path, audio: np.ndarray, sr: int = TARGET_SR) -> None:
    """Write a 1-D float32 numpy array as a 16-bit mono PCM WAV file."""
    audio = np.clip(audio, -1.0, 1.0)
    pcm = (audio * 32767).astype(np.int16)
    with wave.open(str(path), "wb") as wf:
        wf.setnchannels(1)
        wf.setsampwidth(2)
        wf.setframerate(sr)
        wf.writeframes(pcm.tobytes())


# ---------------------------------------------------------------------------
# Human-proxy generator (compressed + decompressed via FFmpeg)
# ---------------------------------------------------------------------------

def load_wav_float32(path: Path) -> np.ndarray:
    """Load existing WAV to float32 numpy array via wave module."""
    with wave.open(str(path), "rb") as wf:
        n = wf.getnframes()
        raw = wf.readframes(n)
        sampwidth = wf.getsampwidth()
        channels = wf.getnchannels()
        sr_file = wf.getframerate()

    if sampwidth == 2:
        audio = np.frombuffer(raw, dtype=np.int16).astype(np.float32) / 32768.0
    elif sampwidth == 4:
        audio = np.frombuffer(raw, dtype=np.int32).astype(np.float32) / 2147483648.0
    else:
        audio = np.frombuffer(raw, dtype=np.uint8).astype(np.float32) / 128.0 - 1.0

    if channels > 1:
        audio = audio.reshape(-1, channels).mean(axis=1)

    if sr_file != TARGET_SR:
        n_new = int(len(audio) * TARGET_SR / sr_file)
        audio = np.interp(
            np.linspace(0, len(audio) - 1, n_new),
            np.arange(len(audio)),
            audio,
        ).astype(np.float32)

    return audio


def make_compressed_human_proxy(source_wav: Path, out_path: Path, bitrate_kbps: int = 32) -> bool:
    """
    Re-encode source_wav to low-bitrate MP3 (broadcast loss simulation),
    then decode back to WAV at 16 kHz.  Returns True on success.

    Ground truth: REAL — because the source is confirmed human speech.
    The compression may introduce spectral artefacts that challenge the classifier.
    """
    mp3_tmp = out_path.with_suffix(".mp3")
    cmd_encode = [
        "ffmpeg", "-y", "-nostdin",
        "-i", str(source_wav),
        "-codec:a", "libmp3lame", "-b:a", f"{bitrate_kbps}k",
        str(mp3_tmp),
    ]
    # Decode to proper WAV (not raw s16le) so audio_loader.wave fallback can read it
    cmd_decode = [
        "ffmpeg", "-y", "-nostdin",
        "-i", str(mp3_tmp),
        "-f", "wav", "-ac", "1", "-ar", str(TARGET_SR),
        str(out_path),
    ]
    try:
        r1 = subprocess.run(cmd_encode, capture_output=True, timeout=30, check=False)
        if r1.returncode != 0:
            return False
        r2 = subprocess.run(cmd_decode, capture_output=True, timeout=30, check=False)
        if r2.returncode != 0:
            return False
        mp3_tmp.unlink(missing_ok=True)
        return True
    except Exception:
        return False



