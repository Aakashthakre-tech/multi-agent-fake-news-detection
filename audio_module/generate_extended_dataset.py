"""
generate_extended_dataset.py
============================
Generates the extended 16-sample test dataset for the TruthLensAI audio detector evaluation.

Dataset design:
  - 8 EXISTING validation_samples (re-used exactly as-is — no modifications).
  - 8 NEW samples generated here, covering:
      * 2 additional human-speech-like WAVs (English + Hindi acoustic profiles)
      * 4 additional synthetic TTS via Windows SAPI (eSpeak via subprocess if available,
        else deterministic scipy-synthesised parametric waveforms labelled SYNTH_SCIPY)
      * 1 compressed-then-decompressed English human-proxy (simulates MP3 broadcast loss)
      * 1 ultra-short (<0.2 s) sample to verify UNCERTAIN guard

Ground-truth labels are determined by construction, not external inference:
  - Human-proxy samples: generated from recorded human audio in validation_samples
    using ffmpeg (re-encode at low bitrate then decode) — provenance is unambiguous.
  - Synthetic samples: generated by deterministic TTS or parametric synthesis;
    provenance is unambiguous by construction.

IMPORTANT: This script NEVER modifies existing files. It writes only to
  audio_module/extended_samples/  (new directory).

Run with:
    .venv\\Scripts\\python.exe audio_module/generate_extended_dataset.py
"""
